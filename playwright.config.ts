import { defineConfig, devices } from "@playwright/test";

/**
 * Браузерные e2e: проверяют то, что нельзя проверить ничем другим — путь
 * пользователя через настоящий интерфейс к настоящему бэкенду.
 *
 * Всё, что можно проверить дешевле, проверяется дешевле: логика — unit'ами,
 * контракт GraphQL — e2e бэкенда через supertest. Сюда попадает только то,
 * что живёт в браузере: рендер, состояние страницы, сеть, которую страница
 * действительно порождает.
 */
export default defineConfig({
	testDir: "./e2e",

	// Прогоны идут по одному и в порядке имён файлов. Причина не в скорости:
	// спеки ходят в ОДНУ базу, и параллельные воркеры на общих данных дают
	// флаки, которые выглядят как баги приложения и съедают день.
	fullyParallel: false,
	workers: 1,

	// `only` в коммите — это тихо выключенные остальные тесты. Локально удобно,
	// в CI недопустимо.
	forbidOnly: !!process.env.CI,
	retries: process.env.CI ? 2 : 0,

	// `list` рассказывает про прогон по ходу, `html` открывается в конце — со
	// всеми шагами, их временем и трейсом упавшего. В CI отчёт только пишется:
	// открывать его там некому, а сервер отчёта держал бы job незакрытым.
	reporter: [["list"], ["html", { open: process.env.CI ? "never" : "on-failure" }]],

	use: {
		baseURL: process.env.E2E_BASE_URL || "http://localhost:3800",

		// Без этого клик по локатору, который никогда не разрешится, ждёт до
		// таймаута ВСЕГО теста — и падение приезжает через минуту, без единого
		// намёка на то, какой шаг завис.
		actionTimeout: 15_000,

		// Трейс только на повторе: он тяжёлый, а нужен ровно тогда, когда тест
		// уже упал. В нём — снимки DOM на каждом шаге, сеть и консоль.
		trace: "on-first-retry",
		screenshot: "only-on-failure",

		// Наблюдаемый прогон: `pnpm e2e` ставит паузу между действиями, чтобы
		// глазами было видно, что происходит. Headless идёт на полной скорости.
		launchOptions: { slowMo: Number(process.env.E2E_SLOWMO ?? 0) },
	},

	projects: [{ name: "chromium", use: { ...devices["Desktop Chrome"] } }],

	// Playwright сам поднимает фронт и ждёт его.
	//
	// ⚠️ `reuseExistingServer` подхватит ЛЮБОЙ процесс, который отвечает на этом
	// порту. Если рядом руками запущен dev-сервер против другого бэкенда —
	// прогон пойдёт по нему и упадёт на пустых списках, а выглядеть это будет
	// как сломанный локатор, а не как не тот контур.
	webServer: {
		command: "pnpm dev",
		url: "http://localhost:3800",
		reuseExistingServer: !process.env.CI,
		timeout: 120_000,
	},
});
